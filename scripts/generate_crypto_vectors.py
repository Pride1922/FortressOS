#!/usr/bin/env python3
"""Extract public RFC vectors, never OpenSSL/BoringSSL fixtures. Not a build step.
Usage: python3 scripts/generate_crypto_vectors.py <directory containing rfc*.txt>
RFC text: https://www.rfc-editor.org/rfc/rfc{8032,4231,8439}.txt
"""
from pathlib import Path
import re
import sys
src=Path(sys.argv[1])
out=['/* Public RFC8032/4231/8439 vectors. Generated by scripts/generate_crypto_vectors.py. */',
     '#ifndef FORTRESS_CRYPTO_VECTORS_H', '#define FORTRESS_CRYPTO_VECTORS_H']
def array(name, data):
    data=bytes.fromhex(data) if isinstance(data,str) else data
    out.append(f'static const uint8_t {name}[{max(1,len(data))}]={{'+','.join(f'0x{x:02x}' for x in data)+'};')
    return len(data)
s=(src/'rfc8032.txt').read_text()
s=s[s.index('-----TEST 1'):s.index('7.2.  Test Vectors for Ed25519ctx',s.index('-----TEST 1'))]
parts=re.split(r'-----TEST [^\n]+',s)[1:]
ed=[]
for i,b in enumerate(parts):
    def field(start,end):
        t=b[b.index(start)+len(start):]
        if end: t=t[:t.index(end)]
        return ''.join(re.findall(r'^\s+([0-9a-f]{2,})\s*$',t,re.M))
    seed=field('SECRET KEY:','PUBLIC KEY:');pk=field('PUBLIC KEY:','MESSAGE')
    m=re.search(r'MESSAGE \(length (\d+) bytes?\):',b)
    msg=field(m.group(0),'SIGNATURE:'); sig=field('SIGNATURE:',None)
    assert len(seed)==64 and len(pk)==64 and len(sig)==128
    assert len(msg)==int(m[1])*2
    for suffix,value in [('seed',seed),('pk',pk),('msg',msg),('sig',sig)]: array(f'ed{i}_{suffix}',value)
    ed.append(f'{{ed{i}_seed,ed{i}_pk,ed{i}_msg,{len(msg)//2},ed{i}_sig}}')
assert len(ed)==5 # pure Ed25519; ctx/ph are different algorithms, not silently substituted
out+=['typedef struct {const uint8_t *seed,*pk,*msg;size_t n;const uint8_t *sig;} ed_vector;',
      'static const ed_vector ed_vectors[]={'+','.join(ed)+'};']
s=(src/'rfc4231.txt').read_text();s=s[s.index('4.2.  Test Case 1',s.index('4.2.  Test Case 1')+1):]
hm=[]
for i in range(1,8):
    b=s.split(f'Test Case {i}',1)[1]
    b=b.split('Test Case',1)[0]
    def value(label):
        p=b.index(label)+len(label);lines=b[p:].splitlines();res=''
        for j,line in enumerate(lines):
            if not line.strip():
                if res: break
                continue
            m=re.match(r'\s*([0-9a-f]{2,})\b',line)
            if not m: break
            res+=m[1]
        return res
    key=value('Key'); msg=value('Data ='); expected=value('HMAC-SHA-256 =')
    # Key lines can have an equals sign before hex.
    if not key:
        key=value('Key =')
    assert key and msg and len(expected) in (32,64),(i,key,msg,expected)
    for suffix,data in [('key',key),('msg',msg),('out',expected)]: array(f'hm{i}_{suffix}',data)
    hm.append(f'{{hm{i}_key,{len(key)//2},hm{i}_msg,{len(msg)//2},hm{i}_out,{len(expected)//2}}}')
out+=['typedef struct {const uint8_t *key;size_t kn;const uint8_t *msg;size_t n;const uint8_t *out;size_t on;} hm_vector;',
      'static const hm_vector hm_vectors[]={'+','.join(hm)+'};']
s=(src/'rfc8439.txt').read_text();s=s[s.index('2.8.2.  Example and Test Vector for AEAD_CHACHA20_POLY1305',8000):]
def dump(label,end):
    t=s[s.index(label)+len(label):];t=t[:t.index(end)]
    return ''.join(''.join(re.findall(r'\b[0-9a-f]{2}\b',line.strip().split('  ',2)[1]))
                   for line in t.splitlines() if re.match(r'\s*\d{3}  ',line))
for name,label,end in [('aead_msg','Plaintext:','AAD:'),('aead_ad','AAD:','Key:'),
                       ('aead_key','Key:','IV:'),('aead_ct','Ciphertext:','AEAD Construction')]:
    assert array(name,dump(label,end)) in (12,32,114)
array('aead_nonce','070000004041424344454647')
array('aead_tag','1ae10b594f09e26a7e902ecbd0600691')
out.append('#endif')
(Path(__file__).resolve().parent.parent/'tests/crypto_vectors.h').write_text('\n'.join(out)+'\n')
